#!/usr/bin/env python3
"""Writes a Hacker's Keyboard 4-row layout (res/xml-<locale>/kbd_qwerty.xml) from a HeliBoard simple layout.

Droidtop/tracker#342, "more layouts". HeliBoard's simple format (heliboard/*.txt, see heliboard/NOTICE) is one key per
line, its label then its long-press keys separated by spaces, with a blank line between rows. Its three letter rows
become the layout's three letter rows; the Shift and Delete keys and every bottom row are copied unchanged from an
existing 4-row layout (the template), so a new language behaves as the others do. The top row's first ten keys also
get the digits 1 to 0 on long press, as every 4-row layout here has.

Usage: heliboard-to-kbd.py <layout.txt> <template kbd_qwerty.xml> <output kbd_qwerty.xml>
"""
import re
import sys

DIGITS = "1234567890"
# Long-press keys this format can hold: one character each, none that Android reads specially at the start of an
# attribute (@ ?) or in it (\ ').
UNSAFE = set("@?\\'")


def escape(text):
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def read_rows(path):
    rows, row = [], []
    for line in open(path, encoding="utf-8").read().split("\n"):
        line = line.strip()
        if not line:
            if row:
                rows.append(row)
                row = []
            continue
        if line.startswith("#"):
            continue
        parts = line.split()
        rows_key = (parts[0], [p for p in parts[1:] if len(p) == 1 and p not in UNSAFE])
        row.append(rows_key)
    if row:
        rows.append(row)
    if len(rows) != 3:
        raise SystemExit(f"{path}: {len(rows)} rows, a 4-row layout takes 3 letter rows")
    for label, _ in (k for r in rows for k in r):
        if len(label) != 1 or label in UNSAFE:
            raise SystemExit(f"{path}: the key '{label}' is not one plain character")
    return rows


def key(label, popups, width=None, edge=None):
    attrs = [f'android:keyLabel="{escape(label)}"']
    if popups:
        attrs.append('android:popupKeyboard="@xml/kbd_popup_template"')
        attrs.append(f'android:popupCharacters="{escape("".join(popups))}"')
    if width:
        attrs.append(f'android:keyWidth="{width}"')
    if edge:
        attrs.append(f'android:keyEdgeFlags="{edge}"')
    return "        <Key\n            " + "\n            ".join(attrs) + " />\n"


def pct(value):
    return f"{value:.4f}".rstrip("0").rstrip(".") + "%p"


def letter_row(keys, header, digits):
    width = 100.0 / len(keys)
    lead = f"\n        {header}" if header else ""
    out = [f"    <Row{lead}\n        android:keyWidth=\"{pct(width)}\"\n    >\n"]
    for i, (label, popups) in enumerate(keys):
        extra = [DIGITS[i]] if digits and i < len(DIGITS) else []
        edge = "left" if i == 0 else "right" if i == len(keys) - 1 else None
        out.append(key(label, extra + [p for p in popups if p not in extra], edge=edge))
    out.append("    </Row>\n")
    return "".join(out)


def main(layout, template, output):
    rows = read_rows(layout)
    text = open(template, encoding="utf-8").read()
    row_spans = [m.span() for m in re.finditer(r"    <Row.*?</Row>\n", text, flags=re.S)]
    third = text[row_spans[2][0]:row_spans[2][1]]
    keys = re.findall(r"<Key\b.*?/>", third, flags=re.S)
    shift, delete = "        " + keys[0] + "\n", "        " + keys[-1] + "\n"
    # The third row: Shift and Delete half as wide again as a letter.
    units = len(rows[2]) + 3
    letter = 100.0 / units
    side = letter * 1.5
    shift = re.sub(r'android:keyWidth="[^"]*"', f'android:keyWidth="{pct(side)}"', shift)
    delete = re.sub(r'android:keyWidth="[^"]*"', f'android:keyWidth="{pct(side)}"', delete)
    row3 = (f"    <Row\n        android:keyWidth=\"{pct(letter)}\"\n    >\n" + shift +
            "".join(key(label, popups) for label, popups in rows[2]) + delete + "    </Row>\n")
    head = text[:row_spans[0][0]]
    head = re.sub(r"<!--.*?-->", "", head, count=1, flags=re.S)
    notice = (
        "<!--\n"
        f"  Generated by input-keyboard/layouts-src/heliboard-to-kbd.py from {layout.split('/')[-1]}\n"
        "  (HeliBoard, GPL-3.0, see layouts-src/heliboard/NOTICE); the Shift, Delete and bottom rows are\n"
        "  the AOSP-derived template's (Apache-2.0). Edit the source layout and run the script again.\n"
        "-->\n"
    )
    head = head.replace("<Keyboard", notice + "\n<Keyboard", 1)
    body = (letter_row(rows[0], 'android:rowEdgeFlags="top"', digits=True) +
            letter_row(rows[1], None, digits=False) + row3)
    tail = text[row_spans[3][0]:]
    out = head + body + tail
    if " -- " in out.split("<Keyboard")[0]:
        raise SystemExit("an XML comment would hold ' -- '")
    open(output, "w", encoding="utf-8").write(out)


if __name__ == "__main__":
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])

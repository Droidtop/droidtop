package dev.droidtop.library.consoles

/**
 * The platform data model. The formerly compiled-in ES_DE_CONSOLE_SYSTEMS
 * list this file used to hold is GONE: platform definitions are data now
 * (platforms-database.json, generated from the same real ES-DE
 * es_systems.xml -- see PlatformsDatabase and docs/SPEC.md 7e2), seeded
 * into ConsoleSystemsRepository's Room store and refreshable from the
 * droidtop-platforms repository.
 *
 * Original provenance note, still true of the generated data: generated from the open-source ES-DE project's own
 * es_systems.xml (gitlab.com/es-de/emulationstation-de, MIT-licensed,
 * resources/systems/linux/es_systems.xml) -- system id, display name, and
 * accepted ROM extensions are ES-DE's real data, generated by a one-off
 * script, not hand-typed or guessed. [retroArchCore], where present, is
 * parsed from that file's first %CORE_RETROARCH%/<core>_libretro.so
 * command entry -- ES-DE's own core name for the Linux build of that
 * libretro core, which is usually (not always -- a few cores differ
 * between platforms) the same base name RetroArch Android ships under
 * <core>_android.so. Not every system has one: many of ES-DE's entries
 * are standalone-emulator-only (MAME, Dolphin, PCSX2, etc.), which have
 * no RetroArch core and need their own am-start Player defined by hand,
 * not generated here.
 */
data class ConsoleSystemDef(
    val id: String,
    val displayName: String,
    val extensions: Set<String>,
    val retroArchCore: String?,
)

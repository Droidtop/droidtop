package dev.droidtop.library.consoles

/**
 * Real standalone-emulator [Player.AmStart] presets, one per (system, real
 * installed emulator app) combination -- generated from Daijishō's own real,
 * public wiki (github.com/TapiocaFox/Daijishou/wiki/Start-Arguments, fetched
 * as raw markdown from raw.githubusercontent.com/wiki/TapiocaFox/Daijishou/
 * Start-Arguments.md), the same real am-start-argument data Daijishō itself
 * ships and documents for its own users -- not fabricated or guessed. Only
 * entries whose Daijishō short-id exactly matched one of droidtop's own
 * real ES_DE_CONSOLE_SYSTEMS ids were kept (see scratchpad's
 * parse_players.py, a one-off generator script, same pattern as
 * EsDeConsoleSystems.kt's own generation) -- RetroArch-core entries were
 * excluded here since droidtop already has real RetroArch support via
 * [DefaultPlayers], generated from ES-DE's own es_systems.xml core mapping.
 *
